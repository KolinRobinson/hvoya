<script setup lang="ts">
import { onMounted, onUnmounted, ref } from 'vue'
import { gsap } from 'gsap'

const svgRef = ref<SVGPathElement | null>(null)
const boxRef = ref<HTMLDivElement | null>(null)

onMounted(() => {
  if (!svgRef.value || !boxRef.value || window.innerWidth < 768) return

  const el = svgRef.value
  const box = boxRef.value

  const handleEnter = (e: MouseEvent) => {
    const rect = el.getBoundingClientRect()
    const centerX = rect.left + rect.width / 2
    const centerY = rect.top + rect.height / 2

    const dx = centerX - e.clientX
    const dy = centerY - e.clientY
    const scale = 80 / Math.hypot(dx, dy)

    gsap.to(el, {
      x: dx * scale,
      y: dy * scale,
      duration: 0.5,
      ease: 'power1.out',
    })
  }

  const handleLeave = () => {
    gsap.to(el, {
      x: 0,
      y: 0,
      duration: 0.8,
      ease: 'elastic.out(1, 0.5)',
    })
  }

  box.addEventListener('mouseenter', handleEnter)
  box.addEventListener('mouseleave', handleLeave)

  onUnmounted(() => {
    box.removeEventListener('mouseenter', handleEnter)
    box.removeEventListener('mouseleave', handleLeave)
  })
})
